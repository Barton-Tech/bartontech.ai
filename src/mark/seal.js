// Seals a page for /mark. The plaintext HTML never goes into this repo.
//
//   MARK_PASSWORD='...' node src/mark/seal.js path/to/deck.html
//
// Writes src/mark/sealed.js. Commit that file; keep deck.html elsewhere.
// Re-running with a new password also changes the password (old cookies stop
// working, so visitors are asked again).
import fs from 'node:fs';
import { seal } from './crypto.js';

const [input] = process.argv.slice(2);
const password = process.env.MARK_PASSWORD;
if (!input || !password) {
  console.error('usage: MARK_PASSWORD=... node src/mark/seal.js <page.html>');
  process.exit(1);
}
const sealed = await seal(fs.readFileSync(input, 'utf8'), password);
const out = new URL('./sealed.js', import.meta.url);
fs.writeFileSync(
  out,
  `// Generated by src/mark/seal.js. AES-GCM ciphertext; see crypto.js.\nexport default ${JSON.stringify(sealed, null, 2)};\n`,
);
console.log(`sealed ${input} -> ${out.pathname} (${sealed.data.length} base64 chars)`);
